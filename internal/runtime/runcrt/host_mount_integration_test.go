// This opt-in test runs only on a disposable VM with root and runc.
//
//nolint:gosec // opt-in disposable VM test; all paths are generated under its private temporary directory
func TestHostMountIntegration(t *testing.T) {
	if os.Getenv("GRAPHENE_TEST_DISPOSABLE_VM") != "1" {
		t.Skip("requires a disposable VM")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	r := New(t.TempDir(), Options{})
	c := host.RunContainer{AgentId: "disk-check", RunId: "mount-check", Image: "test:host-mount",
		Env: map[string]string{"GRAPHENE_TEST_HOST_CHILD": "1", "GRAPHENE_TEST_HOST_SCRIPT": os.Getenv("GRAPHENE_TEST_HOST_SCRIPT")}}
	seedHostTestImage(t, r, c)
	workspace, err := r.workspaceDir(c)
	if err != nil {
		t.Fatal(err)
	}
	defer func() {
		if err := r.Stop(context.Background(), c); err != nil {
			t.Error(err)
		}
	}()
	target := filepath.Join(workspace, "mount")
	defer func() { _ = exec.Command("umount", target).Run() }()
	if err := r.Start(ctx, c); err != nil {
		t.Fatal(err)
	}
	ticker := time.NewTicker(100 * time.Millisecond)
	defer ticker.Stop()
	for {
		if raw, err := os.ReadFile(filepath.Join(workspace, "done")); err == nil {
			if string(raw) != "ok" {
				t.Fatal(string(raw))
			}
			break
		}
		select {
		case <-ctx.Done():
			t.Fatal(ctx.Err())
		case <-ticker.C:
		}
	}
	if out, err := exec.Command("findmnt", "--mountpoint", target).CombinedOutput(); err != nil {
		t.Fatalf("executor mount is invisible on host: %v %s", err, out)
	}
	if raw, err := os.ReadFile(filepath.Join(target, "proof")); err != nil || string(raw) != "mounted" {
		t.Fatalf("host cannot read mounted data: %q %v", raw, err)
	}
}

//nolint:gosec // copies the test executable into a private synthetic image root
func seedHostTestImage(t *testing.T, r *Runtime, c host.RunContainer) {
	t.Helper()
	root := filepath.Join(r.imageDir(c.Image), "rootfs")
	if err := os.MkdirAll(root, 0700); err != nil {
		t.Fatal(err)
	}
	exe, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile(exe)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "probe"), raw, 0700); err != nil {
		t.Fatal(err)
	}
	cfg, err := json.Marshal(imageConfig{Entrypoint: []string{"/probe", "-test.run=^TestHostMountChild$", "-test.v"}})
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(r.imageDir(c.Image), "config.json"), cfg, 0600); err != nil {
		t.Fatal(err)
	}
}

//nolint:gosec // workspace is generated by the parent integration test on a disposable VM
func TestHostMountChild(t *testing.T) {
	if os.Getenv("GRAPHENE_TEST_HOST_CHILD") != "1" {
		t.Skip("executor helper")
	}
	// Positional arguments preserve paths and script contents literally.
	script := `set -eu
printf 'working_directory=%s expected=%s\n' "$(pwd -P)" "$1"
test "$(pwd -P)" = "$1"
mkdir -p "$1/mount"
mount -t tmpfs -o size=1m tmpfs "$1/mount"
printf mounted > "$1/mount/proof"
if [ -n "$2" ]; then /bin/sh "$2"; fi
`
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	cmd := machine.Command(ctx, "/bin/sh", "-c", script, "probe", machine.Workspace(), os.Getenv("GRAPHENE_TEST_HOST_SCRIPT"))
	cmd.Dir = machine.Workspace()
	out, err := cmd.CombinedOutput()
	result := "ok"
	if raw, readErr := os.ReadFile(machine.Path(filepath.Join(machine.Workspace(), "mount", "proof"))); readErr != nil || string(raw) != "mounted" {
		result = "executor file API cannot see the host mount"
	}
	if err != nil {
		result = err.Error() + ": " + string(out)
	}
	if err := os.WriteFile(filepath.Join(machine.Workspace(), "done"), []byte(result), 0600); err != nil {
		t.Fatal(err)
	}
}
